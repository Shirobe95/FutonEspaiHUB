CREATE VIEW public.v_inventory_component_search AS
 WITH base AS (
  SELECT c.id AS relation_id, c.parent_item_code, c.component_item_code, c.quantity, c.relation_type, c.notes, c.created_at, c.created_by,
   p.item_id AS parent_item_id, p.name AS parent_name, p.heca_reference AS parent_heca_reference, p.hub_item_code AS parent_hub_item_code,
   p.woo_id AS parent_woo_id, p.woo_sku AS parent_woo_sku, p.woo_name AS parent_woo_name, p.woo_link_status AS parent_woo_link_status,
   i.item_id AS component_item_id_int, i.name AS component_name, i.heca_reference AS component_heca_reference, i.hub_item_code AS component_hub_item_code,
   i.woo_id AS component_woo_id, i.woo_sku AS component_woo_sku, i.woo_name AS component_woo_name, i.woo_link_status AS component_woo_link_status
  FROM inventory_item_components c
  LEFT JOIN inventory_items p ON COALESCE(p.hub_item_code, p.heca_reference, p.item_id::text) = c.parent_item_code
  LEFT JOIN inventory_items i ON COALESCE(i.hub_item_code, i.heca_reference, i.item_id::text) = c.component_item_code
 ), tokens AS (
  SELECT b.*, b.parent_item_code AS search_token, 'parent_code'::text AS token_type FROM base b WHERE NULLIF(TRIM(BOTH FROM b.parent_item_code), '') IS NOT NULL
  UNION ALL
  SELECT b.*, b.component_item_code, 'component_code'::text FROM base b WHERE NULLIF(TRIM(BOTH FROM b.component_item_code), '') IS NOT NULL
  UNION ALL
  SELECT b.*, TRIM(BOTH FROM token.token), 'woo_sku_token'::text FROM base b
   CROSS JOIN LATERAL regexp_split_to_table(COALESCE(b.parent_woo_sku, ''), '\\|') token(token) WHERE NULLIF(TRIM(BOTH FROM token.token), '') IS NOT NULL
 )
 SELECT relation_id, parent_item_code, parent_item_id, parent_name, parent_heca_reference, parent_hub_item_code, parent_woo_id AS woo_id,
  parent_woo_sku AS woo_sku, parent_woo_name AS woo_name, parent_woo_link_status AS woo_link_status, component_item_code, component_item_id_int,
  component_name, component_heca_reference, component_hub_item_code, component_woo_id, component_woo_sku, component_woo_name, component_woo_link_status,
  quantity, relation_type, notes, search_token, token_type, created_at, created_by FROM tokens;

CREATE VIEW public.v_inventory_hub_search_exact AS
 SELECT lower(TRIM(BOTH FROM i.hub_item_code)) AS search_token_norm, TRIM(BOTH FROM i.hub_item_code) AS search_token, 'direct_hub_item_code'::text AS token_type,
  i.item_id AS result_item_id, i.hub_item_code AS result_item_code, i.item_record_type AS result_record_type, i.name AS result_name, i.family AS result_family,
  i.subgroup AS result_subgroup, i.woo_id AS result_woo_id, i.woo_parent_id AS result_woo_parent_id, i.woo_sku AS result_woo_sku,
  NULL::text AS related_item_code, NULL::text AS related_name, NULL::numeric AS relation_quantity, NULL::text AS relation_type
  FROM inventory_items i WHERE NULLIF(TRIM(BOTH FROM COALESCE(i.hub_item_code, '')), '') IS NOT NULL
 UNION ALL
 SELECT lower(TRIM(BOTH FROM i.item_id::text)), TRIM(BOTH FROM i.item_id::text), 'direct_item_id'::text, i.item_id, i.hub_item_code, i.item_record_type, i.name, i.family, i.subgroup,
  i.woo_id, i.woo_parent_id, i.woo_sku, NULL::text, NULL::text, NULL::numeric, NULL::text FROM inventory_items i WHERE i.item_id IS NOT NULL
 UNION ALL
 SELECT lower(TRIM(BOTH FROM i.heca_reference)), TRIM(BOTH FROM i.heca_reference), 'direct_heca_reference'::text, i.item_id, i.hub_item_code, i.item_record_type, i.name, i.family, i.subgroup,
  i.woo_id, i.woo_parent_id, i.woo_sku, NULL::text, NULL::text, NULL::numeric, NULL::text FROM inventory_items i WHERE NULLIF(TRIM(BOTH FROM COALESCE(i.heca_reference, '')), '') IS NOT NULL
 UNION ALL
 SELECT lower(TRIM(BOTH FROM i.woo_sku)), TRIM(BOTH FROM i.woo_sku), 'direct_woo_sku_full'::text, i.item_id, i.hub_item_code, i.item_record_type, i.name, i.family, i.subgroup,
  i.woo_id, i.woo_parent_id, i.woo_sku, NULL::text, NULL::text, NULL::numeric, NULL::text FROM inventory_items i WHERE NULLIF(TRIM(BOTH FROM COALESCE(i.woo_sku, '')), '') IS NOT NULL
 UNION ALL
 SELECT lower(TRIM(BOTH FROM c.component_item_code)), TRIM(BOTH FROM c.component_item_code),
  CASE WHEN c.relation_type = 'alias' THEN 'alias_base_match'::text ELSE 'component_match'::text END,
  p.item_id, c.parent_item_code, p.item_record_type, COALESCE(p.name, c.parent_name), p.family, p.subgroup, COALESCE(p.woo_id, c.woo_id), p.woo_parent_id, COALESCE(p.woo_sku, c.woo_sku),
  c.component_item_code, COALESCE(ci.name, c.component_name), c.quantity, c.relation_type
  FROM inventory_item_components c
  LEFT JOIN inventory_items p ON p.hub_item_code = c.parent_item_code OR p.heca_reference = c.parent_item_code OR p.item_id::text = c.parent_item_code
  LEFT JOIN inventory_items ci ON ci.hub_item_code = c.component_item_code OR ci.heca_reference = c.component_item_code OR ci.item_id::text = c.component_item_code
  WHERE NULLIF(TRIM(BOTH FROM COALESCE(c.component_item_code, '')), '') IS NOT NULL
 UNION ALL
 SELECT lower(TRIM(BOTH FROM c.parent_item_code)), TRIM(BOTH FROM c.parent_item_code), 'relation_parent_match'::text,
  p.item_id, c.parent_item_code, p.item_record_type, COALESCE(p.name, c.parent_name), p.family, p.subgroup, COALESCE(p.woo_id, c.woo_id), p.woo_parent_id, COALESCE(p.woo_sku, c.woo_sku),
  c.component_item_code, COALESCE(ci.name, c.component_name), c.quantity, c.relation_type
  FROM inventory_item_components c
  LEFT JOIN inventory_items p ON p.hub_item_code = c.parent_item_code OR p.heca_reference = c.parent_item_code OR p.item_id::text = c.parent_item_code
  LEFT JOIN inventory_items ci ON ci.hub_item_code = c.component_item_code OR ci.heca_reference = c.component_item_code OR ci.item_id::text = c.component_item_code
  WHERE NULLIF(TRIM(BOTH FROM COALESCE(c.parent_item_code, '')), '') IS NOT NULL;

CREATE VIEW public.v_inventory_hub_search_ranked AS
 WITH ranked AS (
  SELECT s.search_token_norm, s.search_token, s.token_type, s.result_item_id, s.result_item_code, s.result_record_type, s.result_name, s.result_family, s.result_subgroup,
   s.result_woo_id, s.result_woo_parent_id, s.result_woo_sku, s.related_item_code, s.related_name, s.relation_quantity, s.relation_type,
   CASE WHEN s.token_type='direct_hub_item_code' THEN 10 WHEN s.token_type='direct_heca_reference' THEN 20 WHEN s.token_type='direct_item_id' THEN 25
    WHEN s.token_type='direct_woo_sku_full' THEN 30 WHEN s.token_type='relation_parent_match' THEN 35 WHEN s.token_type='alias_parent_match' THEN 40
    WHEN s.token_type='alias_base_match' THEN 50 WHEN s.token_type='component_match' THEN 60 WHEN s.token_type='woo_sku_token' THEN 70 ELSE 999 END AS match_priority,
   row_number() OVER (PARTITION BY lower(TRIM(BOTH FROM COALESCE(s.search_token_norm, ''))), s.result_item_id, COALESCE(s.related_item_code, ''), COALESCE(s.relation_type, ''), COALESCE(s.relation_quantity::text, '')
    ORDER BY (CASE WHEN s.token_type='direct_hub_item_code' THEN 10 WHEN s.token_type='direct_heca_reference' THEN 20 WHEN s.token_type='direct_item_id' THEN 25
    WHEN s.token_type='direct_woo_sku_full' THEN 30 WHEN s.token_type='relation_parent_match' THEN 35 WHEN s.token_type='alias_parent_match' THEN 40
    WHEN s.token_type='alias_base_match' THEN 50 WHEN s.token_type='component_match' THEN 60 WHEN s.token_type='woo_sku_token' THEN 70 ELSE 999 END), s.result_item_code, s.related_item_code) AS rn
  FROM v_inventory_hub_search_exact s)
 SELECT search_token_norm, search_token, result_item_id, result_item_code, result_record_type, result_name, result_family, result_subgroup, result_woo_id,
  result_woo_parent_id, result_woo_sku, related_item_code, related_name, relation_quantity, relation_type, token_type AS best_token_type, match_priority
 FROM ranked WHERE rn = 1;

