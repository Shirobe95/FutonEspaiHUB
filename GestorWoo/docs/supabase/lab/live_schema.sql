CREATE OR REPLACE FUNCTION public.futonhub_write_audit_log(p_operation_id text, p_user_id uuid, p_user_email text, p_role text, p_device_id uuid, p_machine_name text, p_module text, p_action text, p_status text, p_severity text DEFAULT 'INFO'::text, p_entity_type text DEFAULT NULL::text, p_entity_id text DEFAULT NULL::text, p_before_data jsonb DEFAULT NULL::jsonb, p_after_data jsonb DEFAULT NULL::jsonb, p_message text DEFAULT NULL::text, p_error_detail text DEFAULT NULL::text)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $function$
declare v_profile public.profiles%rowtype; v_id uuid; v_severity text; v_status text;
begin
  if auth.uid() is null or p_user_id is null or p_user_id <> auth.uid() then
    raise exception 'FutonHUB blackbox: usuario autenticado no coincide con p_user_id';
  end if;
  select * into v_profile from public.profiles where id = auth.uid() and active = true limit 1;
  if v_profile.id is null then raise exception 'FutonHUB blackbox: usuario no valido o inactivo para audit_log'; end if;
  if v_profile.role not in ('admin', 'worker') then raise exception 'FutonHUB blackbox: rol no autorizado para audit_log'; end if;
  if p_user_email is not null and lower(p_user_email) <> lower(v_profile.email) then
    raise exception 'FutonHUB blackbox: email no coincide con el perfil autenticado';
  end if;
  v_severity := upper(coalesce(nullif(p_severity, ''), 'INFO'));
  if v_severity not in ('INFO', 'WARNING', 'ERROR', 'CRITICAL') then v_severity := 'INFO'; end if;
  v_status := upper(coalesce(nullif(p_status, ''), 'OK'));
  insert into public.audit_logs(operation_id,user_id,user_email,role,device_id,machine_name,module,action,entity_type,entity_id,severity,status,before_data,after_data,message,error_detail)
  values (p_operation_id,v_profile.id,v_profile.email,v_profile.role,p_device_id,p_machine_name,p_module,p_action,p_entity_type,p_entity_id,v_severity,v_status,p_before_data,p_after_data,p_message,p_error_detail)
  returning id into v_id;
  return jsonb_build_object('id', v_id,'operation_id', p_operation_id,'user_id', v_profile.id,'user_email', v_profile.email,'role', v_profile.role,'module', p_module,'action', p_action,'status', v_status,'severity', v_severity);
end;
$function$;

